# Emit IAS15's per-coordinate work as orbit-sequencer programs.
#
# Every operation of IAS15 except the gravity (which couples lanes) and
# the convergence test (a reduction over lanes) is elementwise over the
# 3N coordinates: one lane per coordinate, the same instruction stream
# for every lane, constants from the bank. That is the shape
# cft-fp256's sequencer and its 512-entry constant bank exist to run,
# and this file writes it down as .cfta text (docs/PROGRAMS.md of the
# pinned cft-fp256) so that cft-asm can assemble it and ias15_cft
# --engine program can run it through cft_program_run_ex.
#
# The programs use the FMA form of the scheme (--arith fma): no
# division, because a correctly rounded divide is not a sequencer
# program (cft-fp256's docs/ORBITS.md, obstacle 2). The constants are
# per-run data (BANK_EXT) because two of them depend on dt.
#
#   predict-<fmt>     x at substep n from b, a0, v0, x0, csx
#                     streams: a = x0, b = v0, c = a0
#                     scratch in: b0..b6, csx (8 slots)
#                     bank: K0..K6 = h_n (j+1)/(j+3) for j = 6..0,
#                           D2 = fl(dt h_n)/2, D1 = fl(dt h_n)
#                     deposit: x
#   correct<n>-<fmt>  the g and b update at substep n, n = 1..7
#                     streams: a = at (the acceleration at the substep)
#                     scratch in/out: a0, g0..g6, b0..b6, csb0..csb6 (22 slots)
#                     bank: R0..R_{n-1} = 1/rr, C0..C_{n-2} = c
#                     deposit: tmp = g_new - g_old (the convergence measure)
#
# The instruction order is exactly the host loop's in --arith fma
# mode; the check is that the two engines produce identical bits.

import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
outdir = os.path.join(root, "programs")

FORMATS = ["fp64", "fp128", "fp256"]

HEADER = """; %s - generated by tools/gen_programs.py, do not edit.
; SPDX-License-Identifier: GPL-3.0-or-later
; %s
"""


def predict(fmt):
    L = [HEADER % ("predict-" + fmt, "IAS15 position predictor at one substep, FMA form; see tools/gen_programs.py")]
    L.append(".format   %s" % fmt)
    L.append(".deposits 1")
    L.append(".bank     external")
    for i in range(7):
        L.append(".const    K%d" % i)
    L.append(".const    D2")
    L.append(".const    D1")
    L.append(".scratch  in 8")
    for i in range(7):
        L.append(".slot     B%d = %d" % (i, i))
    L.append(".slot     CSX = 7")
    L.append(".reg      x0 = r0")
    L.append(".reg      v0 = r1")
    L.append(".reg      a0 = r2")
    L.append(".reg      t  = r3")
    L.append(".reg      s  = r4")
    L.append("")
    L.append("ldl  t, B6")
    for i, j in enumerate(range(5, -1, -1)):
        L.append("ldl  s, B%d" % j)
        L.append("fma  t, t, K%d, s" % i)           # t = t*K_i + b_j
    L.append("fma  t, t, K6, a0")                   # + a0 level
    L.append("fma  t, t, D2, v0")                   # *dt*h/2 + v0
    L.append("mul  t, t, D1")                       # *dt*h
    L.append("ldl  s, CSX")
    L.append("sub  t, t, s")                        # xk = P - csx
    L.append("add  t, t, x0")                       # x = xk + x0
    L.append("deposit t")
    L.append("halt")
    return "\n".join(L) + "\n"


def predict_ens(fmt):
    """The predictor for an ensemble whose systems keep their own
    adaptive steps: fl(dt h_n) and its half are per LANE, so they ride
    in the scratch block (slots 8 and 9) instead of the bank, and the
    bank holds only the seven format-wide K constants. The arithmetic
    is instruction for instruction the same as predict()'s; the two
    constants are loaded into a register first."""
    L = [HEADER % ("predict-ens-" + fmt, "IAS15 position predictor at one substep, FMA form, per-lane dt; see tools/gen_programs.py")]
    L.append(".format   %s" % fmt)
    L.append(".deposits 1")
    L.append(".bank     external")
    for i in range(7):
        L.append(".const    K%d" % i)
    L.append(".scratch  in 10")
    for i in range(7):
        L.append(".slot     B%d = %d" % (i, i))
    L.append(".slot     CSX = 7")
    L.append(".slot     D2L = 8")
    L.append(".slot     D1L = 9")
    L.append(".reg      x0 = r0")
    L.append(".reg      v0 = r1")
    L.append(".reg      a0 = r2")
    L.append(".reg      t  = r3")
    L.append(".reg      s  = r4")
    L.append("")
    L.append("ldl  t, B6")
    for i, j in enumerate(range(5, -1, -1)):
        L.append("ldl  s, B%d" % j)
        L.append("fma  t, t, K%d, s" % i)           # t = t*K_i + b_j
    L.append("fma  t, t, K6, a0")                   # + a0 level
    L.append("ldl  s, D2L")
    L.append("fma  t, t, s, v0")                    # *dt*h/2 + v0, this lane's dt
    L.append("ldl  s, D1L")
    L.append("mul  t, t, s")                        # *dt*h
    L.append("ldl  s, CSX")
    L.append("sub  t, t, s")                        # xk = P - csx
    L.append("add  t, t, x0")                       # x = xk + x0
    L.append("deposit t")
    L.append("halt")
    return "\n".join(L) + "\n"


def add_cs(L, p, cs, inp, y, t, u):
    """Kahan's add_cs exactly as REBOUND writes it: y = inp - cs; t = p + y;
    cs = (t - p) - y; p = t. Registers p and cs are updated in place;
    p receives t through an exact copysign."""
    L.append("sub  %s, %s, %s" % (y, inp, cs))
    L.append("add  %s, %s, %s" % (t, p, y))
    L.append("sub  %s, %s, %s" % (u, t, p))
    L.append("sub  %s, %s, %s" % (cs, u, y))
    L.append("copysign %s, %s, %s" % (p, t, t))


def correct(fmt, n):
    L = [HEADER % ("correct%d-%s" % (n, fmt), "IAS15 corrector at substep %d, FMA form; see tools/gen_programs.py" % n)]
    L.append(".format   %s" % fmt)
    L.append(".deposits 1")
    L.append(".bank     external")
    for m in range(n):
        L.append(".const    RINV%d" % m)
    for m in range(n - 1):
        L.append(".const    COEF%d" % m)
    L.append(".scratch  in 22")
    L.append(".scratch  out 22")
    L.append(".slot     SLOT_A0 = 0")
    for m in range(7):
        L.append(".slot     G%d = %d" % (m, 1 + m))
    for m in range(7):
        L.append(".slot     B%d = %d" % (m, 8 + m))
    for m in range(7):
        L.append(".slot     CSB%d = %d" % (m, 15 + m))
    regs = {"at": "r0", "gk": "r3", "gkcs": "r4", "y": "r5", "t": "r6", "u": "r7", "a0": "r8",
            "q": "r9", "gm": "r10", "tmp": "r11", "prod": "r12", "bm": "r13", "csbm": "r14", "zero": "r15", "nega0": "r16"}
    for k, v in regs.items():
        L.append(".reg      %s = %s" % (k, v))
    L.append("")
    # gk = at; gk_cs = gravity_cs (+0); add_cs(gk, gk_cs, -a0); add_cs(gk, gk_cs, csa0 (+0))
    L.append("ldl  a0, SLOT_A0")
    L.append("neg  nega0, a0")
    L.append("copysign gk, at, at")          # gk = at; gkcs is r4, which starts at +0
    add_cs(L, "gk", "gkcs", "nega0", "y", "t", "u")
    add_cs(L, "gk", "gkcs", "zero", "y", "t", "u")   # csa0 is +0 with basic gravity
    # q = gk*R0; for m = 1..n-1: q = (q - g[m-1]) * R[m]
    L.append("mul  q, gk, RINV0")
    for m in range(1, n):
        L.append("ldl  gm, G%d" % (m - 1))
        L.append("sub  q, q, gm")
        L.append("mul  q, q, RINV%d" % m)
    # tmp = q - g_old; g[n-1] = q
    L.append("ldl  gm, G%d" % (n - 1))
    L.append("sub  tmp, q, gm")
    L.append("stl  q, G%d" % (n - 1))
    # b_m += tmp*C_m (compensated), m = 0..n-2; b_{n-1} += tmp
    for m in range(n - 1):
        L.append("ldl  bm, B%d" % m)
        L.append("ldl  csbm, CSB%d" % m)
        L.append("mul  prod, tmp, COEF%d" % m)
        add_cs(L, "bm", "csbm", "prod", "y", "t", "u")
        L.append("stl  bm, B%d" % m)
        L.append("stl  csbm, CSB%d" % m)
    L.append("ldl  bm, B%d" % (n - 1))
    L.append("ldl  csbm, CSB%d" % (n - 1))
    add_cs(L, "bm", "csbm", "tmp", "y", "t", "u")
    L.append("stl  bm, B%d" % (n - 1))
    L.append("stl  csbm, CSB%d" % (n - 1))
    L.append("deposit tmp")
    L.append("halt")
    return "\n".join(L) + "\n"


# ---- gravity (ROUND3.md, P1) ------------------------------------------
#
# REBOUND's reb_gravity_basic_calculate_acceleration() as a handful of
# program runs a force evaluation, where it was 22 elementwise calls over
# the P pairs and one more over the 3N coordinates per partner. Gravity
# couples lanes, so two of the runs read their inputs through an index
# table (cft_run_args.idx_scratch_in, ABI 0.14) - or, on the route that
# takes the host's gather instead, through a block the host filled from
# the same table. The programs are the same either way, which is what
# makes the two routes the same bits (src/ias15_cft.c, vprog_ix()).
#
#   gravity-pair-<fmt>   one lane a pair: dx, dy, dz and
#                        dx*dx + dy*dy + dz*dz + softening2
#                        stream a: softening2, broadcast
#                        scratch in: x_i, x_j, y_i, y_j, z_i, z_j (6 slots)
#                        scratch out: dx, dy, dz (3 slots)
#                        deposit: the squared distance
#   gravity-cube-<fmt>   one lane a pair: _r*_r*_r, left to right
#                        stream a: _r, from cft_sqrt
#                        deposit: _r^3, which cft_div divides G by
#   gravity-force-<fmt>  one lane a pair: what each of its bodies receives
#                        streams: a = G/_r^3, b = m_i, c = m_j
#                        scratch in: dx, dy, dz (gravity-pair's out block)
#                        deposits: prefactj*dx, *dy, *dz, then
#                        prefacti*dx, *dy, *dz (6) - the fold's pool
#   gravity-fold<K>-<fmt>  one lane a coordinate: the running sum
#                        (stream a) plus K slots, in slot order
#                        scratch in: the next K addends of the lane's
#                        row, through the fold table into the pool,
#                        CFT_IDX_NONE (+0) past the row's end
#                        deposit: the running sum
#
# The square root and the divide stay library calls: a correctly rounded
# divide is not a sequencer program (cft-fp256 docs/ORBITS.md, obstacle
# 2), which is also why --engine program needs --arith fma. Nothing else
# here needs either, so these programs carry REBOUND's own roundings and
# run at --arith rebound, in every engine mode, and in both halves.
#
# The order is the gate: every expression below is the elementwise code's
# (and so REBOUND's) operation for operation, and the fold adds a row's
# addends one at a time from the sum it was given, which starts at +0 -
# REBOUND's `ax = 0; ax += ...`. Registers stay below r16 and there is no
# constant bank, so each image needs SCRATCH and SCRATCH_IO and nothing
# else (cft-asm -i).
#
# The fold comes in every power-of-two width up to 256 slots, the
# assembler's default scratch depth (docs/PROGRAMS.md of the pinned tree,
# `.scratch N`): a run takes the narrowest that holds what is left of the
# rows, so a short row costs at most twice its own length in +0 adds, and
# a longer one takes several runs, each continuing the last one's sum.
GRAVITY_FOLD_WIDTHS = [1 << i for i in range(9)]


def gravity_pair(fmt):
    L = [HEADER % ("gravity-pair-" + fmt, "gravity's pair arithmetic up to the square root; see tools/gen_programs.py")]
    L.append(".format   %s" % fmt)
    L.append(".deposits 1")
    L.append(".scratch  in 6")
    L.append(".scratch  out 3")
    # Slot names share the register namespace and ignore case
    # (docs/PROGRAMS.md), hence S_ for every slot.
    for i, name in enumerate(("S_XI", "S_XJ", "S_YI", "S_YJ", "S_ZI", "S_ZJ")):
        L.append(".slot     %s = %d" % (name, i))
    for i, name in enumerate(("S_DX", "S_DY", "S_DZ")):
        L.append(".slot     %s = %d" % (name, i))
    for k, v in (("soft2", "r0"), ("pi", "r3"), ("pj", "r4"), ("dx", "r5"), ("dy", "r6"), ("dz", "r7"),
                 ("s", "r8"), ("t", "r9")):
        L.append(".reg      %s = %s" % (k, v))
    L.append("")
    for d, (i, j) in zip(("dx", "dy", "dz"), (("S_XI", "S_XJ"), ("S_YI", "S_YJ"), ("S_ZI", "S_ZJ"))):
        L.append("ldl  pi, %s" % i)
        L.append("ldl  pj, %s" % j)
        L.append("sub  %s, pi, pj" % d)              # d = x_i - x_j (the ghost box's +0 is not added)
    L.append("mul  s, dx, dx")                      # dx*dx + dy*dy + dz*dz + softening2, left to right
    L.append("mul  t, dy, dy")
    L.append("add  s, s, t")
    L.append("mul  t, dz, dz")
    L.append("add  s, s, t")
    L.append("add  s, s, soft2")
    L.append("stl  dx, S_DX")
    L.append("stl  dy, S_DY")
    L.append("stl  dz, S_DZ")
    L.append("deposit s")
    L.append("halt")
    return "\n".join(L) + "\n"


def gravity_cube(fmt):
    L = [HEADER % ("gravity-cube-" + fmt, "gravity's _r*_r*_r; see tools/gen_programs.py")]
    L.append(".format   %s" % fmt)
    L.append(".deposits 1")
    L.append(".reg      rad = r0")
    L.append(".reg      t = r3")
    L.append("")
    L.append("mul  t, rad, rad")                    # _r*_r*_r, left to right
    L.append("mul  t, t, rad")
    L.append("deposit t")
    L.append("halt")
    return "\n".join(L) + "\n"


def gravity_force(fmt):
    L = [HEADER % ("gravity-force-" + fmt, "gravity's prefactors and the six contributions of a pair; see tools/gen_programs.py")]
    L.append(".format   %s" % fmt)
    L.append(".deposits 6")
    L.append(".scratch  in 3")
    for i, name in enumerate(("S_DX", "S_DY", "S_DZ")):
        L.append(".slot     %s = %d" % (name, i))
    for k, v in (("prefact", "r0"), ("mi", "r1"), ("mj", "r2"), ("negp", "r3"), ("pfj", "r4"), ("pfi", "r5"),
                 ("dx", "r6"), ("dy", "r7"), ("dz", "r8"), ("c", "r9")):
        L.append(".reg      %s = %s" % (k, v))
    L.append("")
    L.append("neg  negp, prefact")                  # prefactj = -prefact*m_j
    L.append("mul  pfj, negp, mj")
    L.append("mul  pfi, prefact, mi")               # prefacti = prefact*m_i
    L.append("ldl  dx, S_DX")
    L.append("ldl  dy, S_DY")
    L.append("ldl  dz, S_DZ")
    for pf in ("pfj", "pfi"):                       # what i receives, then what j receives
        for d in ("dx", "dy", "dz"):
            L.append("mul  c, %s, %s" % (pf, d))
            L.append("deposit c")
    L.append("halt")
    return "\n".join(L) + "\n"


def gravity_fold(fmt, k):
    L = [HEADER % ("gravity-fold%d-%s" % (k, fmt), "gravity's accumulate, %d addends a run; see tools/gen_programs.py" % k)]
    L.append(".format   %s" % fmt)
    L.append(".deposits 1")
    L.append(".scratch  in %d" % k)
    L.append(".reg      sum = r0")
    L.append(".reg      acc = r3")
    L.append(".reg      t = r4")
    L.append("")
    for s in range(k):
        L.append("ldl  t, %d" % s)
        L.append("add  acc, %s, t" % ("sum" if s == 0 else "acc"))   # the sum so far, plus the next addend
    L.append("deposit acc")
    L.append("halt")
    return "\n".join(L) + "\n"


def write_gravity(fmt):
    """Write one format's gravity programs; return their file names."""
    progs = [("gravity-pair", gravity_pair(fmt)), ("gravity-cube", gravity_cube(fmt)),
             ("gravity-force", gravity_force(fmt))]
    progs += [("gravity-fold%d" % k, gravity_fold(fmt, k)) for k in GRAVITY_FOLD_WIDTHS]
    names = []
    for stem, text in progs:
        name = "%s-%s.cfta" % (stem, fmt)
        with open(os.path.join(outdir, name), "w", newline="\n") as f:
            f.write(text)
        names.append(name)
    return names


def main():
    os.makedirs(outdir, exist_ok=True)
    names = []
    for fmt in FORMATS:
        name = "predict-%s.cfta" % fmt
        with open(os.path.join(outdir, name), "w", newline="\n") as f:
            f.write(predict(fmt))
        names.append(name)
        name = "predict-ens-%s.cfta" % fmt
        with open(os.path.join(outdir, name), "w", newline="\n") as f:
            f.write(predict_ens(fmt))
        names.append(name)
        for n in range(1, 8):
            name = "correct%d-%s.cfta" % (n, fmt)
            with open(os.path.join(outdir, name), "w", newline="\n") as f:
                f.write(correct(fmt, n))
            names.append(name)
        names += write_gravity(fmt)
    print("wrote %d programs under %s" % (len(names), outdir))
    return 0


if __name__ == "__main__":
    sys.exit(main())
