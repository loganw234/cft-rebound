# Sequencer program images, compiled into the binary.
#
#   python tools/embed_programs.py --asm <cft-asm> --name <family> \
#                                  --out <header> <stem>-<fmt>.cfta ...
#
# The library half of src/ias15_cft.c (the drop-in and the Python DLL)
# loads nothing from disk: load_one() and load_programs() are the
# standalone program's alone. So a route whose new half is a program run
# can be taken there only if its image is compiled in. This assembles
# each .cfta with the given cft-asm - the pinned clone's, which is what
# makes the bits the pin's - and writes one header that holds every
# image as bytes, plus a table of them:
#
#   static const struct cft_embedded_image <family>_images[];
#   static const size_t <family>_images_n;
#
# The type is src/cft_embedded_image.h's, defined there once so that two
# families can share one translation unit. Every other symbol this
# writes begins with <family>_.
#
# THE HEADER IS WRITTEN ONLY WHEN ITS BYTES CHANGE. `make programs`
# rewrites every programs/*.cfta on each suite run, so a header that
# followed their timestamps would rebuild the engine each time - and on
# Windows a relink alone changes the binary's bytes (the PE timestamp,
# measured 2026-11-02), which changes every gate-cache key that names
# it, so `make check-quick` could never skip. The comparison is on the
# whole header, so an image that did change is always written.
#
# What a header carries is checked against its own source of truth by
# its own family's gate: the gravity images against programs/out/ (by
# SHA-256, tools/check_gravity.py).

import argparse
import hashlib
import os
import re
import subprocess
import sys
import tempfile

FORMATS = ("fp32", "fp64", "fp128", "fp256")
NAME = re.compile(r"^[a-z][a-z0-9_]*$")


def fail(msg):
    print("embed_programs: " + msg, file=sys.stderr)
    sys.exit(2)


def split_name(path):
    """<stem>-<fmt>.cfta, by its file name: the format is what follows the
    last '-', and it must be one of the four."""
    base = os.path.basename(path)
    if not base.endswith(".cfta"):
        fail("%s: expected a .cfta source" % path)
    stem, dash, fmt = base[:-len(".cfta")].rpartition("-")
    if not dash or not stem or fmt not in FORMATS:
        fail("%s: the name must be <stem>-<format>.cfta with the format one of %s"
             % (path, ", ".join(FORMATS)))
    return stem, fmt


def assemble(asm, src, tmp):
    out = os.path.join(tmp, os.path.basename(src)[:-len(".cfta")] + ".cftp")
    p = subprocess.run([asm, src, "-o", out], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    if p.returncode != 0 or not os.path.exists(out):
        fail("%s %s failed (rc %d): %s" % (asm, src, p.returncode, (p.stderr or p.stdout).strip()))
    with open(out, "rb") as f:
        return f.read()


def render(family, images):
    guard = family.upper() + "_IMAGES_H"
    L = ["/* %s_images.h - generated by tools/embed_programs.py, do not edit." % family,
         " * SPDX-License-Identifier: GPL-3.0-or-later",
         " *",
         " * The %s family's sequencer program images, assembled by the pinned" % family,
         " * cft-asm from these sources and compiled in, for the library half,",
         " * which loads nothing from disk:",
         " *"]
    for stem, fmt, src, data in images:
        L.append(" *   %s-%s.cfta  %d bytes  sha256 %s" % (stem, fmt, len(data), hashlib.sha256(data).hexdigest()))
    L += [" */",
          "#ifndef " + guard,
          "#define " + guard,
          '#include "cft_embedded_image.h"',
          ""]
    for i, (stem, fmt, src, data) in enumerate(images):
        L.append("static const unsigned char %s_image_%d[%d] = {   /* %s-%s */" % (family, i, len(data), stem, fmt))
        for j in range(0, len(data), 24):
            L.append("    " + ",".join(str(b) for b in data[j:j + 24]) + ",")
        L.append("};")
    L.append("")
    L.append("static const struct cft_embedded_image %s_images[] = {" % family)
    for i, (stem, fmt, src, data) in enumerate(images):
        L.append('    { "%s", "%s", %s_image_%d, sizeof %s_image_%d },' % (stem, fmt, family, i, family, i))
    L.append("};")
    L.append("static const size_t %s_images_n = sizeof %s_images / sizeof %s_images[0];" % (family, family, family))
    L.append("#endif")
    return ("\n".join(L) + "\n").encode("ascii")


def main():
    ap = argparse.ArgumentParser(description="compile sequencer program images into a C header")
    ap.add_argument("--asm", required=True, help="the cft-asm to assemble with")
    ap.add_argument("--name", required=True, help="the family: every symbol is <name>_...")
    ap.add_argument("--out", required=True, help="the header to write")
    ap.add_argument("sources", nargs="+", help="<stem>-<format>.cfta files")
    args = ap.parse_args()
    if not NAME.match(args.name):
        fail("--name %r: a family is a C identifier in lower case" % args.name)
    seen = set()
    images = []
    with tempfile.TemporaryDirectory() as tmp:
        for src in sorted(args.sources, key=lambda s: os.path.basename(s)):
            stem, fmt = split_name(src)
            if (stem, fmt) in seen:
                fail("%s-%s is given twice" % (stem, fmt))
            seen.add((stem, fmt))
            images.append((stem, fmt, src, assemble(args.asm, src, tmp)))
    text = render(args.name, images)
    try:
        with open(args.out, "rb") as f:
            old = f.read()
    except OSError:
        old = None
    if old == text:
        print("embed_programs: %s unchanged, %d images" % (args.out, len(images)))
        return 0
    d = os.path.dirname(os.path.abspath(args.out))
    os.makedirs(d, exist_ok=True)
    tmpout = args.out + ".tmp"
    with open(tmpout, "wb") as f:
        f.write(text)
    os.replace(tmpout, args.out)
    print("embed_programs: wrote %s, %d images" % (args.out, len(images)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
