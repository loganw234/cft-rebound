# Sequencer program images, compiled into the engine: the library half of
# src/ias15_cft.c loads nothing from disk, so a route whose new half is a
# program run carries its image in the binary. One family a header.
#
#   python tools/embed_programs.py --asm <cft-asm> --name <family> \
#                                  --out <header> <stem>-<fmt>.cfta ...
#
# Each .cfta is assembled by the given cft-asm. The header includes
# src/cft_embedded_image.h and defines
#     static const struct cft_embedded_image <family>_images[];
#     static const size_t <family>_images_n;
# and every other symbol it defines begins with <family>_. It is
# rewritten only when its bytes would change, so a source that is merely
# touched does not relink the engine.
#
# The interface is the round's one (the lead's urgent/lead-embedded-
# images.md, 2026-11-02): P1 owns this tool, and this copy is P2's
# stand-in for it. Checking an image against its source of truth is the
# family's own gate's job, through cft_program_digest().

import argparse
import os
import re
import subprocess
import sys


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--asm", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("sources", nargs="+")
    args = ap.parse_args()
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", args.name):
        sys.exit("embed_programs: --name %s is not a C identifier" % args.name)
    work = args.out + ".d"
    os.makedirs(work, exist_ok=True)
    rows, body = [], []
    for src in args.sources:
        m = re.fullmatch(r"(.+)-(fp32|fp64|fp128|fp256)\.cfta", os.path.basename(src))
        if not m:
            sys.exit("embed_programs: %s is not named <stem>-<format>.cfta" % src)
        stem, fmt = m.groups()
        image = os.path.join(work, "%s-%s.cftp" % (stem, fmt))
        if subprocess.run([args.asm, src, "-o", image]).returncode:
            sys.exit("embed_programs: %s did not assemble %s" % (args.asm, src))
        with open(image, "rb") as f:
            data = f.read()
        sym = "%s_%s_%s" % (args.name, re.sub(r"\W", "_", stem), fmt)
        body.append("/* %s: %d bytes, assembled from %s */" % (os.path.basename(image), len(data), src.replace("\\", "/")))
        body.append("static const unsigned char %s[%d] = {" % (sym, len(data)))
        body += ["    " + " ".join("0x%02x," % b for b in data[i:i + 12]) for i in range(0, len(data), 12)]
        body.append("};")
        rows.append('    { "%s", "%s", %s, %d },' % (stem, fmt, sym, len(data)))
    guard = "CFT_REBOUND_%s_IMAGES_H" % args.name.upper()
    text = "\n".join(["/* GENERATED by tools/embed_programs.py --name %s. Do not edit: make rewrites it. */" % args.name,
                      "#ifndef " + guard, "#define " + guard, '#include "cft_embedded_image.h"', ""]
                     + body + ["", "static const struct cft_embedded_image %s_images[] = {" % args.name] + rows
                     + ["};", "static const size_t %s_images_n = sizeof %s_images / sizeof %s_images[0];"
                        % (args.name, args.name, args.name), "#endif", ""])
    try:
        with open(args.out, encoding="utf-8", newline="") as f:
            if f.read() == text:
                print("embed_programs: %s unchanged, %d images" % (args.out, len(rows)))
                return 0
    except FileNotFoundError:
        pass
    with open(args.out + ".tmp", "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(args.out + ".tmp", args.out)
    print("embed_programs: wrote %s, %d images" % (args.out, len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
